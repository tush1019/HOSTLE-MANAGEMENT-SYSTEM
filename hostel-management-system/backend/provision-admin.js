/* ============================================================
   HOSTELHUB — First-admin provisioning (setup script)
   Usage:
     ADMIN_NAME="Hostel Admin" ADMIN_EMAIL=admin@hostel.example \
     ADMIN_PASSWORD="<strong-unique-password>" node backend/provision-admin.js

   Creates the very first Administrator account only when no admin
   exists yet. Never creates credentials automatically — you must
   supply ADMIN_EMAIL and ADMIN_PASSWORD. The Admin ID (e.g. ADM0001)
   is generated by the backend and shown once.
   ============================================================ */
require("dotenv").config();
const bcrypt = require("bcryptjs");
const db = require("./db");

(async () => {
  try {
    const name = String(process.env.ADMIN_NAME || "Hostel Administrator").trim();
    const email = String(process.env.ADMIN_EMAIL || "").trim().toLowerCase();
    const password = String(process.env.ADMIN_PASSWORD || "");

    if (!email || !/^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/.test(email)) {
      console.error("Set ADMIN_EMAIL to a valid email address.");
      process.exit(1);
    }
    if (!password || password.length < 8) {
      console.error("Set ADMIN_PASSWORD to at least 8 characters.");
      process.exit(1);
    }

    const pool = await db.getPool();
    if (!pool) {
      console.error("Database unavailable. Start the backend first (it auto-runs migrations).");
      process.exit(1);
    }

    const [existing] = await pool.query("SELECT id FROM users WHERE role = 'Admin' LIMIT 1");
    if (existing.length > 0) {
      console.log("An administrator already exists. Provisioning skipped.");
      process.exit(0);
    }

    const [dup] = await pool.query("SELECT id FROM users WHERE email = ? LIMIT 1", [email]);
    if (dup.length > 0) {
      console.error("An account with this email already exists.");
      process.exit(1);
    }

    const passwordHash = await bcrypt.hash(password, 12);
    const [result] = await pool.query(
      `INSERT INTO users (name, email, password, role, email_verified) VALUES (?, ?, ?, 'Admin', 1)`,
      [name, email, passwordHash]
    );
    const userId = result.insertId;
    const adminId = `ADM${String(userId).padStart(4, "0")}`;
    await pool.query(
      `UPDATE users SET admin_id = ? WHERE id = ?`,
      [adminId, userId]
    );
    await pool.query(`INSERT INTO user_profiles (user_id, email) VALUES (?, ?)`, [userId, email]);

    const [adminRow] = await pool.query("SELECT admin_id FROM users WHERE id = ? LIMIT 1", [userId]);

    console.log("\n=== First administrator provisioned ===");
    console.log("Name:", name);
    console.log("Email:", email);
    console.log("Admin ID:", adminRow[0].admin_id);
    console.log("Password: (as supplied via ADMIN_PASSWORD — store it securely)");
    console.log("=======================================\n");
    process.exit(0);
  } catch (error) {
    console.error("Provisioning failed:", error.message);
    process.exit(1);
  }
})();
